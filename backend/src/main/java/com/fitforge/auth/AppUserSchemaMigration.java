package com.fitforge.auth;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.Ordered;
import org.springframework.core.annotation.Order;
import org.springframework.dao.DataAccessException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.util.List;

/**
 * Keeps the physical user table aligned with {@link AppUser} on PostgreSQL.
 *
 * Hibernate ddl-auto=update is the first line of defence, but production can
 * override it through HIBERNATE_DDL_AUTO and older Neon schemas may predate
 * profile columns such as activity_level. These statements are idempotent and
 * never drop or rewrite existing user data.
 */
@Component
@Order(Ordered.HIGHEST_PRECEDENCE)
public class AppUserSchemaMigration implements ApplicationRunner {
    private static final Logger LOG = LoggerFactory.getLogger(AppUserSchemaMigration.class);

    // AppUser is mapped to "users"; "app_users" is migrated too when a legacy
    // deployment has that physical table, but it is never created here.
    private static final String USER_TABLE = "users";
    private static final String LEGACY_USER_TABLE = "app_users";

    private static final List<String> COLUMN_DEFINITIONS = List.of(
            "id BIGINT GENERATED BY DEFAULT AS IDENTITY",
            "name VARCHAR(120) NOT NULL DEFAULT 'User'",
            "email VARCHAR(190) NOT NULL DEFAULT ''",
            "password VARCHAR(100) NOT NULL DEFAULT ''",
            "target_calories INTEGER NOT NULL DEFAULT 1800",
            "token_version INTEGER NOT NULL DEFAULT 0",
            "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP",
            "height_cm DOUBLE PRECISION",
            "age_years INTEGER",
            "gender VARCHAR(20)",
            "activity_level VARCHAR(30)",
            "primary_goal VARCHAR(40)",
            "secondary_goal VARCHAR(40)"
    );

    private final JdbcTemplate jdbc;
    private final DataSource dataSource;

    public AppUserSchemaMigration(JdbcTemplate jdbc, DataSource dataSource) {
        this.jdbc = jdbc;
        this.dataSource = dataSource;
    }

    @Override
    public void run(ApplicationArguments args) {
        if (!isPostgreSql()) {
            return;
        }
        migrateUserTable();
        migrateLegacyTableIfPresent();
    }

    private boolean isPostgreSql() {
        try (Connection connection = dataSource.getConnection()) {
            DatabaseMetaData metaData = connection.getMetaData();
            return metaData != null && "PostgreSQL".equalsIgnoreCase(metaData.getDatabaseProductName());
        } catch (Exception ex) {
            LOG.warn("Could not determine database product; skipping AppUser schema migration", ex);
            return false;
        }
    }

    private void migrateUserTable() {
        try {
            if (!tableExists(USER_TABLE)) {
                jdbc.execute("CREATE TABLE IF NOT EXISTS " + USER_TABLE + " (" +
                        String.join(", ", COLUMN_DEFINITIONS) +
                        ", PRIMARY KEY (id), CONSTRAINT uq_users_email UNIQUE (email))");
                LOG.info("Created missing {} table for AppUser", USER_TABLE);
            }
            addMissingColumns(USER_TABLE);
            backfillDefaults(USER_TABLE);
            LOG.info("AppUser schema migration verified for {}", USER_TABLE);
        } catch (DataAccessException ex) {
            LOG.error("AppUser schema migration failed for {}", USER_TABLE, ex);
            throw new IllegalStateException("AppUser schema migration failed for " + USER_TABLE, ex);
        }
    }

    private void migrateLegacyTableIfPresent() {
        try {
            if (!tableExists(LEGACY_USER_TABLE)) {
                return;
            }
            addMissingColumns(LEGACY_USER_TABLE);
            backfillDefaults(LEGACY_USER_TABLE);
            LOG.info("AppUser schema migration verified for legacy {}", LEGACY_USER_TABLE);
        } catch (DataAccessException ex) {
            // The mapped table is "users"; a legacy app_users table must not block startup.
            LOG.warn("Legacy {} schema migration skipped after failure", LEGACY_USER_TABLE, ex);
        }
    }

    private boolean tableExists(String table) {
        Integer count = jdbc.queryForObject(
                "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = ?",
                Integer.class,
                table);
        return count != null && count > 0;
    }

    private void addMissingColumns(String table) {
        for (String definition : COLUMN_DEFINITIONS) {
            jdbc.execute("ALTER TABLE " + table + " ADD COLUMN IF NOT EXISTS " + definition);
        }
    }

    private void resyncIdSequence(String table) {
        // A stale identity/serial sequence makes every insert fail with a duplicate-key
        // integrity error, which registration would otherwise misreport as a duplicate email.
        jdbc.execute("SELECT setval(pg_get_serial_sequence('" + table + "', 'id'), COALESCE((SELECT MAX(id) FROM " + table + "), 1), true) WHERE pg_get_serial_sequence('" + table + "', 'id') IS NOT NULL");
    }

    private void relaxLegacyNotNullColumns(String table) {
        // Legacy tables can carry NOT NULL columns that AppUser no longer maps
        // (production had one named "role"). Hibernate inserts omit them, so every
        // registration failed with SQLState 23502. Give such columns a safe default.
        List<String> mapped = COLUMN_DEFINITIONS.stream()
                .map(definition -> definition.substring(0, definition.indexOf(' ')))
                .toList();
        List<String[]> legacy = jdbc.query(
                "SELECT column_name, data_type FROM information_schema.columns " +
                        "WHERE table_schema = current_schema() AND table_name = ? " +
                        "AND is_nullable = 'NO' AND column_default IS NULL",
                (rs, row) -> new String[]{rs.getString(1), rs.getString(2)},
                table);
        for (String[] column : legacy) {
            String name = column[0];
            if (mapped.contains(name) || !name.matches("[a-z_][a-z0-9_]*")) continue;
            String fallback = switch (column[1]) {
                case "character varying", "character", "text" -> "'" + ("role".equals(name) ? "USER" : "") + "'";
                case "smallint", "integer", "bigint", "numeric", "double precision", "real" -> "0";
                case "boolean" -> "false";
                case "timestamp without time zone", "timestamp with time zone", "date" -> "CURRENT_TIMESTAMP";
                default -> null;
            };
            if (fallback == null) continue;
            jdbc.execute("ALTER TABLE " + table + " ALTER COLUMN " + name + " SET DEFAULT " + fallback);
            jdbc.update("UPDATE " + table + " SET " + name + " = " + fallback + " WHERE " + name + " IS NULL");
            LOG.info("Set safe default for legacy NOT NULL column {}.{}", table, name);
        }
    }

    private void backfillDefaults(String table) {
        relaxLegacyNotNullColumns(table);
        resyncIdSequence(table);
        jdbc.update("UPDATE " + table + " SET target_calories = 1800 WHERE target_calories IS NULL");
        jdbc.update("UPDATE " + table + " SET token_version = 0 WHERE token_version IS NULL");
        jdbc.update("UPDATE " + table + " SET created_at = CURRENT_TIMESTAMP WHERE created_at IS NULL");
        jdbc.update("UPDATE " + table + " SET name = COALESCE(NULLIF(BTRIM(email), ''), 'User') WHERE name IS NULL OR BTRIM(name) = ''");
    }
}
